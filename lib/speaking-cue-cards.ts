/** Speaking Part 2 cue cards shared by the interactive studio and its server-rendered guide. */

export interface CueCardData {
  id: string;
  topic: string;
  title: string;
  prompt: string;
  bullets: string[];
  followUp: string;
  vocabTips: { phrase: string; meaning: string }[];
  /** Band 8–9 sample answer (paragraphs separated by a blank line). */
  modelTranscript: string;
  /** Explicit SEO slug for /speaking-practice/[slug]; falls back to the id without "card-". */
  slug?: string;
  /** Example keyword notes a candidate could jot down in the 1-minute preparation time. */
  prepNotes?: string[];
  /** Part 3 discussion questions linked to the card's theme. */
  part3Questions?: string[];
}

/** URL slug for a cue card's topic page (/speaking-practice/[slug]). */
export function cueCardSlug(card: Pick<CueCardData, "id" | "slug">): string {
  return card.slug ?? card.id.replace(/^card-/, "");
}

/** Canonical path for a cue card's topic page. */
export function cueCardPath(card: Pick<CueCardData, "id" | "slug">): string {
  return `/speaking-practice/${cueCardSlug(card)}`;
}

/** Looks up a cue card by its page slug. */
export function findCueCardBySlug(slug: string): CueCardData | undefined {
  return SAMPLE_CUE_CARDS.find((card) => cueCardSlug(card) === slug);
}

